const KEY = "todo-aka-quote-deck";
const PERIODS = ["Утро", "День", "Вечер"];

type Memory = { day: string; slot: number; index: number; seen: number[] };

function slotOf(now: Date) {
  const hour = now.getHours();
  if (hour < 12) return 0;
  if (hour < 18) return 1;
  return 2;
}

function read(): Memory | null {
  try {
    const raw = localStorage.getItem(KEY);
    if (!raw) return null;
    const data = JSON.parse(raw) as Memory;
    if (!data || typeof data.index !== "number" || !Array.isArray(data.seen)) return null;
    return data;
  } catch {
    return null;
  }
}

function write(memory: Memory) {
  if (typeof localStorage === "undefined") return;
  localStorage.setItem(KEY, JSON.stringify(memory));
}

export function quoteForNow(now = new Date()) {
  const day = dayKey(now);
  const slot = slotOf(now);
  const saved = read();
  if (saved && saved.day === day && saved.slot === slot && QUOTES[saved.index]) {
    return { ...QUOTES[saved.index], period: PERIODS[slot] };
  }
  const seen = new Set(saved?.seen ?? []);
  let pool = QUOTES.map((_, index) => index).filter((index) => !seen.has(index));
  let reset = false;
  if (pool.length === 0) {
    pool = QUOTES.map((_, index) => index).filter((index) => index !== saved?.index);
    reset = true;
  }
  const index = pool[Math.floor(Math.random() * pool.length)] ?? 0;
  write({ day, slot, index, seen: reset ? [index] : [...seen, index] });
  return { ...QUOTES[index]!, period: PERIODS[slot]! };
}
